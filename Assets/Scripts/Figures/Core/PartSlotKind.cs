namespace Figures
{
    /// <summary>
    /// Тип гнезда — он же группа взаимозаменяемости. Деталь входит в любое свободное
    /// гнездо своего типа: рука — в любое плечо, нога — в любое бедро. Парные гнёзда
    /// различаются только номером и ничем не ограничивают деталь.
    ///
    /// Это физическая посадка, а не правильность: чужая рука встаёт так же, как своя.
    /// </summary>
    public enum PartSlotKind
    {
        Head = 0,
        Hair = 1,
        Face = 2,
        Torso = 3,
        Arm = 4,
        Leg = 5,

        /// <summary>
        /// Тазовая область: отдельная деталь между торсом и ногами. Номер новый и
        /// последний намеренно — Unity сериализует enum по номеру, и вставка в середину
        /// молча превратила бы в готовых ассетах торсы в тазы.
        /// </summary>
        Pelvis = 6
    }
}
