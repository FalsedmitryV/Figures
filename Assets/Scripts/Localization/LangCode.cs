/// <summary>
/// Языки проекта. Имя значения = имя файла таблицы в Resources/Lang
/// (RU → ru.csv). Набор по умолчанию — языки, которые принимает Яндекс Игры.
///
/// Значение без своей csv-таблицы = ошибка в консоли при переключении, поэтому
/// добавляй и убирай языки вместе с файлами в Resources/Lang.
///
/// Новые языки — только в конец: enum сериализуется числом (LocalizedTextTMP
/// хранит язык шрифта), и вставка в середину молча сдвинет настройки в сценах.
/// Имя — ISO-код, который отдаёт платформа (белорусский — BE, не BY), тогда
/// YandexLocalizationProvider сопоставит его без правок.
/// </summary>
public enum LangCode
{
    EN,
    ES,
    KK,
    RU,
    TR,
    DE,
    BE
}
